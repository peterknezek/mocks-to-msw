import { createMockHandler } from "./index.js";

// Define mock data imports
const mocks = {
  "/api/user/GET": import("./GET.json"),
  "/uniq/POST": import("./GET.json"),
} as const;

// Create mock handler with type checking
const { mock } = createMockHandler({
  mocks,
  debug: true,
});

// Define response types
interface User {
  id: string;
  name: string;
  email: string;
}

// Valid mock calls - these will pass type checking
mock.get<User>("/api/user"); // OK: matches GET method
mock.post("/uniq"); // OK: matches POST method

// Invalid mock calls - these will show type errors
// mock.get("/uniq"); // Error: "/uniq" is only for POST
// mock.post("/api/user"); // Error: "/api/user" is only for GET

// Example with response modifier
mock.get<User>("/api/user", (user) => ({
  ...user,
  name: user.name.toUpperCase(),
}));

// Example with an OpenAPI schema generated by openapi-typescript (see src/fixtures/api-schema.ts).
// The modifier argument is typed from the schema by the URI, no per-call generic needed.
import type { paths } from "./fixtures/api-schema.js";

const schemaMocks = {
  "/client/GET": import("./GET.json"),
  "/client/application/POST": import("./GET.json"),
  "/users/123/GET": import("./GET.json"),
} as const;

const { mock: typedMock } = createMockHandler<keyof typeof schemaMocks, paths>({ mocks: schemaMocks });

// `user` is components["schemas"]["User"]
typedMock.get("/client", (user) => ({ ...user, name: user.name.toUpperCase() }));

// `application` is the 201 response of POST /client/application
typedMock.post("/client/application", (application) => ({ ...application, status: "approved" }));

// "/users/123" is matched to the schema path "/users/{id}"
typedMock.get("/users/123", (user) => user.email);
