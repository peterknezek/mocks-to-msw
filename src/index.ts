import { http, HttpResponse } from "msw";

type SupportedMethods = Extract<keyof typeof http, "get" | "post" | "put" | "delete">;
type Method = Uppercase<SupportedMethods>;
type Path = `${string}/${Method}`;

/**
 * Extracts the base URL from a path by removing the method suffix
 */
type ExtractBaseUrl<T extends Path> = T extends `${infer U}/${Method}` ? U : never;

/**
 * Maps methods to their allowed paths
 */
type MethodToPath<P extends Path> = {
  [M in Method]: ExtractBaseUrl<Extract<P, `${string}/${M}`>>;
};

/**
 * Function with can be modified the response data.
 */
type ModifierFn<R> = (json: R) => any;

type MockImport = Promise<{ default: any }>;

type MocksRequestReturn = ReturnType<typeof http.get>;

/**
 * Type of the modifier argument when no schema is given, or when the schema has no match for the request.
 */
type DefaultResponse = Record<string, any>;

/* ------------------------------------------------------------------------------------------------
 * OpenAPI schema support
 *
 * `createMockHandler<keyof typeof mocks, paths>()` accepts the `paths` interface generated by
 * openapi-typescript (https://openapi-ts.dev). The types below resolve the URI given to
 * `mock.<method>()` to a key of that interface and pick the JSON body of its success response,
 * so the modifier argument is typed without a per-call generic.
 * ---------------------------------------------------------------------------------------------- */

/**
 * Counts the segments of a path ("/users/{id}" → 3), so a template only matches a URL of the same depth.
 */
type Depth<S extends string, N extends 0[] = []> = S extends `${string}/${infer Tail}`
  ? Depth<Tail, [...N, 0]>
  : N["length"];

/**
 * "/users/{id}" → "/users/:id" (the MSW parameter syntax).
 */
type ToMswPath<S extends string> = S extends `${infer Head}{${infer Param}}${infer Tail}`
  ? `${Head}:${Param}${ToMswPath<Tail>}`
  : S;

/**
 * "/users/{id}" → `/users/${string}`, so a captured value such as "/users/123" is assignable to it.
 */
type ToPattern<S extends string> = S extends `${infer Head}{${string}}${infer Tail}`
  ? `${Head}${string}${ToPattern<Tail>}`
  : S;

/**
 * MSW-style path → original key. Plain string-literal keys, computed once per `paths` interface.
 */
type MswPathMap<Paths> = { [K in keyof Paths & string as ToMswPath<K>]: K };

/**
 * Keys whose pattern the URL is assignable to, as a distributive conditional over the keys
 * (one template-literal check per path, no intermediate object or template-literal union).
 * `${string}` also swallows slashes, so "/users/{id}" would match "/users/1/posts/2":
 * only candidates with the same segment depth as the URL are kept.
 */
type PatternMatches<Keys, Url extends string> = Keys extends string
  ? Url extends ToPattern<Keys>
    ? Depth<Keys> extends Depth<Url>
      ? Keys
      : never
    : never
  : never;

/**
 * Resolves the URI given to `mock.<method>()` to a key of the `paths` interface:
 * 1. exact key ("/client"), 2. MSW parameter form ("/users/:id"), 3. captured value ("/users/123").
 * An exact key wins, so "/users/me" is not also matched by "/users/{id}".
 */
type ResolvePathKey<Paths, Url extends string> = Url extends keyof Paths
  ? Url
  : Url extends keyof MswPathMap<Paths>
    ? MswPathMap<Paths>[Url]
    : PatternMatches<keyof Paths, Url>;

/**
 * Status codes (as emitted by openapi-typescript) that count as the mocked success response.
 */
type SuccessStatus = 200 | 201 | 202 | 203 | 204 | 205 | 206 | 207 | 208 | 226 | "2XX" | "default";

/**
 * Picks the JSON body of a response object: "application/json" first, then any other JSON media type.
 */
type JsonBody<Res> = Res extends { content: infer C }
  ? C extends { "application/json": infer J }
    ? J
    : { [MT in keyof C]: MT extends `${string}json${string}` ? C[MT] : never }[keyof C]
  : never;

type SuccessJson<Operation> = Operation extends { responses: infer R }
  ? { [S in keyof R]: S extends SuccessStatus ? JsonBody<R[S]> : never }[keyof R]
  : never;

type OperationOf<Paths, Key, M extends Lowercase<Method>> = Key extends keyof Paths
  ? Paths[Key] extends { [K in M]: infer Op }
    ? Op
    : never
  : never;

type OrDefault<T> = [T] extends [never] ? DefaultResponse : T;

/**
 * Response JSON type of `[M] Url` according to an openapi-typescript `paths` interface.
 * Falls back to `DefaultResponse` when there is no schema, no matching path or method, or no JSON body.
 */
type ResponseOf<Paths, Url extends string, M extends Lowercase<Method>> = OrDefault<
  SuccessJson<OperationOf<Paths, ResolvePathKey<Paths, Url>, M>>
>;

const createMocksRequest =
  <P extends Path>(options: CreateMockHandlerOptions<P>) =>
  <Res>(method: Method, pathname: string, modifier?: ModifierFn<Res>) => {
    const { mocks, debug, origin } = options;
    const getMock = async () => {
      try {
        const mockPath = `${pathname}/${method}` as P;
        const data = await mocks[mockPath].then((res) => res.default);
        if (debug) {
          console.info(`[mocks-to-msw] Mock file was loaded. [${method}]: "${pathname}"`);
        }
        if (typeof modifier === "function") {
          return HttpResponse.json(modifier(data));
        }
        return HttpResponse.json(data);
      } catch (error) {
        if (debug) {
          console.error(`[mocks-to-msw] Mock file was not found. [${method}]: "${pathname}"`, error);
        }
      }
    };

    // Construct the URL from the given pathname and domain.
    const url = ((): string => {
      if (origin) {
        try {
          return new URL(pathname, origin).href;
        } catch (e) {
          if (debug) {
            console.error(
              `[mocks-to-msw] Invalid URL. The provided option for a createMockHandler, the URL's origin, has the issue. Values: [origin]: "${origin}" [pathname]: "${pathname}"`,
              e
            );
          }
          return pathname;
        }
      }
      return pathname;
    })();

    switch (method) {
      case "GET":
        return http.get(url, getMock);
      case "POST":
        return http.post(url, getMock);
      case "PUT":
        return http.put(url, getMock);
      case "DELETE":
        return http.delete(url, getMock);
      default:
        throw new Error(`Invalid method: ${String(method satisfies never)}`);
    }
  };

/**
 * A `mock.<method>()` function.
 *
 * The first overload types the modifier argument from the `Schema` (an openapi-typescript `paths`
 * interface) by the given URI. The second keeps the explicit `mock.get<ResponseType>(uri)` form.
 */
type MockFn<P extends Path, Schema, M extends Method> = {
  /**
   * @param uri The URI to intercept.
   * @param modifier A function that modifies the response data. Its argument is typed from the schema.
   */
  <Uri extends MethodToPath<P>[M]>(
    uri: Uri,
    modifier?: ModifierFn<ResponseOf<Schema, Uri, Lowercase<M>>>
  ): MocksRequestReturn;
  /**
   * @param uri The URI to intercept.
   * @param modifier A function that modifies the response data of the given `ResponseType`.
   */
  <ResponseType = DefaultResponse>(uri: MethodToPath<P>[M], modifier?: ModifierFn<ResponseType>): MocksRequestReturn;
};

type MockNamespace<P extends Path, Schema> = {
  /**
   * Mocks a GET request to the given URI.
   * @example
   * ```ts
   * mock.get('/api/user')
   * mock.get('/api/user', (json) => ({ ...json, data: 'modified' }))
   * ```
   */
  get: MockFn<P, Schema, "GET">;
  /**
   * Mocks a POST request to the given URI.
   * @example
   * ```ts
   * mock.post('/api/user')
   * mock.post('/api/user', (json) => ({ ...json, data: 'modified' }))
   * ```
   */
  post: MockFn<P, Schema, "POST">;
  /**
   * Mocks a PUT request to the given URI.
   * @example
   * ```ts
   * mock.put('/api/user')
   * mock.put('/api/user', (json) => ({ ...json, data: 'modified' }))
   * ```
   */
  put: MockFn<P, Schema, "PUT">;
  /**
   * Mocks a DELETE request to the given URI.
   * @example
   * ```ts
   * mock.delete('/api/user')
   * mock.delete('/api/user', (json) => ({ ...json, data: 'modified' }))
   * ```
   */
  delete: MockFn<P, Schema, "DELETE">;
};

const createMockNamespace = <P extends Path, Schema>(
  options: CreateMockHandlerOptions<P>
): MockNamespace<P, Schema> => {
  const mocksRequest = createMocksRequest(options);
  return {
    get: (uri: MethodToPath<P>["GET"], modifier?: ModifierFn<any>) => mocksRequest("GET", uri, modifier),
    post: (uri: MethodToPath<P>["POST"], modifier?: ModifierFn<any>) => mocksRequest("POST", uri, modifier),
    put: (uri: MethodToPath<P>["PUT"], modifier?: ModifierFn<any>) => mocksRequest("PUT", uri, modifier),
    delete: (uri: MethodToPath<P>["DELETE"], modifier?: ModifierFn<any>) => mocksRequest("DELETE", uri, modifier),
  };
};

interface CreateMockHandlerOptions<Paths extends Path> {
  /**
   * A record of mock imports for each path.
   * @example
   * ```ts
   * const mocks = {
   *   '/api/user/GET': import('./api/user/GET.json'),
   *   '/api/user/POST': import('./api/user/POST.json'),
   * } as const;
   * ```
   */
  mocks: Record<Paths, MockImport>;
  /**
   * A flag to enable debug logs.
   */
  debug?: boolean;
  /**
   * Origin of the URL, that is its scheme, its domain and its port.
   * @example "https://api.example.com"
   */
  origin?: string;
}

/**
 * Creates a mock handler with the given options.
 * @typeParam P The union of mock keys, usually `keyof typeof mocks`.
 * @typeParam Schema Optional `paths` interface generated by openapi-typescript. When given, the
 * modifier argument of `mock.get('/api/user', (json) => ...)` is typed from the schema by the URI.
 * @param options The options to create a mock handler.
 * @example
 * ```ts
 * const mocks = {
 *   '/api/user/GET': import('./api/user/GET.json'),
 *   '/api/user/POST': import('./api/user/POST.json'),
 * } as const;
 *
 * const { mock } = createMockHandler<keyof typeof mocks>({
 *   mocks,
 * });
 * ```
 * @example
 * ```ts
 * import type { paths } from './api-schema'; // openapi-typescript output
 *
 * const { mock } = createMockHandler<keyof typeof mocks, paths>({ mocks });
 *
 * // `user` is typed as the JSON body of the 2xx response of `GET /api/user`
 * mock.get('/api/user', (user) => ({ ...user, name: user.name.toUpperCase() }));
 * ```
 */
export const createMockHandler = <P extends Path, Schema = unknown>(options: CreateMockHandlerOptions<P>) => ({
  /**
   * A namespace to intercept and mock HTTP requests.
   *
   * @example
   * ```ts
   * mock.get('/api')
   * mock.post('/api/:id', modifier)
   * ```
   */
  mock: createMockNamespace<P, Schema>(options),
});
